"""Measure the generated bottle photograph and derive the sand grid's interior from it.

    python -I bottle_geo.py <bottle.jpg> <out.json> [debug.png]

The bottle was shot straight-on on black, so each row of the glass is one bright span. Per row:
outer half-width (symmetrised about the bottle axis), then the interior = the outline eroded by the
wall thickness (thick in the neck, thin in the body), cut at the floor of the bottle. The result is
the half-width of the interior per grid row, in cells, plus the crop that maps the photo onto the grid.
"""
import json
import sys

import numpy as np
from PIL import Image, ImageDraw

SRC, OUT = sys.argv[1], sys.argv[2]
DBG = sys.argv[3] if len(sys.argv) > 3 else None

AXIS = 897.0          # bottle axis in the photo (px)
CELL = 4              # photo px per grid cell
GRID_W = 300          # cells across the grid canvas
TOP = -160            # photo y of grid row 0 (above the photo: padded with black)
GRID_H = 602          # rows
MOUTH_Y = 214         # photo y of the first interior row (just under the top of the lip)
FLOOR_Y = 2026        # photo y of the floor's front edge (top of the thick base)
NECK_END = 520        # the neck bore is straight down to here
R_NECK, R_BODY = 44, 17

im = np.asarray(Image.open(SRC).convert('L')).astype(np.float32)
H, W = im.shape
# box blur along x so single dark pixels inside a bright wall don't split the span
k = 7
pad = np.pad(im, ((0, 0), (k // 2, k // 2)), mode='edge')
cs = np.cumsum(pad, axis=1)
sm = (cs[:, k - 1:] - np.concatenate([np.zeros((H, 1)), cs[:, :-k]], axis=1)) / k
outer = np.zeros(H)
for y in range(H):
    row = sm[y, 200:1600]
    idx = np.where(row > 38)[0]
    if len(idx):
        l, r = idx[0] + 200, idx[-1] + 200
        outer[y] = max(AXIS - l, r - AXIS)
for y in range(1, H - 1):
    if outer[y] == 0 and outer[y - 1] and outer[y + 1]:
        outer[y] = (outer[y - 1] + outer[y + 1]) / 2
sm_outer = outer.copy()
for y in range(2, H - 2):
    sm_outer[y] = np.median(outer[y - 2:y + 3])


def radius(y):
    if y <= NECK_END:
        return R_NECK
    if y >= NECK_END + 160:
        return R_BODY
    t = (y - NECK_END) / 160
    return R_NECK + (R_BODY - R_NECK) * t


inner = np.zeros(H)
for y in range(MOUTH_Y, FLOOR_Y):
    r = radius(y)
    ri = int(np.ceil(r))
    best = 1e9
    for dy in range(-ri, ri + 1):
        yy = y + dy
        if 0 <= yy < H:
            best = min(best, sm_outer[yy] - np.sqrt(max(0.0, r * r - dy * dy)))
    inner[y] = max(0.0, best)
# the neck bore is straight: from the mouth to the end of the neck it is the narrowest neck value
bore = inner[NECK_END - 120:NECK_END].min()
for y in range(MOUTH_Y, NECK_END + 1):
    inner[y] = bore
# monotone from the end of the neck down to the widest point (no pinches from highlights)
peak = int(np.argmax(inner[:FLOOR_Y]))
for y in range(NECK_END + 1, peak + 1):
    inner[y] = max(inner[y], inner[y - 1])
# the inner floor meets the wall in a curve
CORNER = 40
base_hw = inner[FLOOR_Y - CORNER - 1]
for y in range(FLOOR_Y - CORNER, FLOOR_Y):
    dy = y - (FLOOR_Y - CORNER)
    inner[y] = min(inner[y], base_hw - CORNER + np.sqrt(max(0, CORNER * CORNER - dy * dy)))

rows = []
for gy in range(GRID_H):
    y0 = TOP + gy * CELL
    ys = [y for y in range(y0, y0 + CELL) if MOUTH_Y <= y < FLOOR_Y]
    rows.append(round(float(np.mean([inner[y] for y in ys])) / CELL, 2) if len(ys) == CELL else 0)
mouth = next(i for i, v in enumerate(rows) if v > 0)
bottom = max(i for i, v in enumerate(rows) if v > 0) + 1
geo = {
    'W': GRID_W, 'H': GRID_H, 'cx': GRID_W / 2, 'mouth': mouth, 'bottom': bottom,
    'crop': [AXIS - GRID_W * CELL / 2, TOP, GRID_W * CELL, GRID_H * CELL],
    'hw': rows,
}
if OUT.endswith('.js'):
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('// Generated by design/works/sand/scripts/bottle_geo.py from the bottle photograph:\n'
                '// the interior half-width per grid row (cells), the mouth and floor rows, the photo crop.\n'
                'export default ' + json.dumps(geo, separators=(',', ':')) + ';\n')
else:
    json.dump(geo, open(OUT, 'w'), separators=(',', ':'))
cap = sum(sum(1 for x in range(GRID_W) if abs(x + 0.5 - GRID_W / 2) < v) for v in rows if v > 0)
print('mouth', mouth, 'bottom', bottom, 'neck hw', rows[mouth], 'body hw', max(rows), 'capacity', cap)

if DBG:
    rgb = Image.open(SRC).convert('RGB')
    d = ImageDraw.Draw(rgb)
    for y in range(MOUTH_Y, FLOOR_Y, 2):
        d.point((AXIS - inner[y], y), fill=(255, 0, 128))
        d.point((AXIS + inner[y], y), fill=(255, 0, 128))
        d.point((AXIS - sm_outer[y], y), fill=(0, 200, 255))
        d.point((AXIS + sm_outer[y], y), fill=(0, 200, 255))
    d.line((0, FLOOR_Y, W, FLOOR_Y), fill=(255, 255, 0))
    d.line((0, MOUTH_Y, W, MOUTH_Y), fill=(255, 255, 0))
    rgb.thumbnail((900, 1200))
    rgb.save(DBG)

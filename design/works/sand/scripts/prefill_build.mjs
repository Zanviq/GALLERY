// Pours the opening bottles once, here, and stores them for the page (dev tool, not deployed).
//   node design/works/sand/scripts/prefill_build.mjs
// Writes works/sand/js/start.js: two bottles as run-length colour runs over the interior cells
// (row by row), so the page shows swept layers on its first frame instead of computing them.
//   START: about a quarter full, for the opening pour to continue
//   STILL: about two thirds full, the bottle shown as it is under prefers-reduced-motion
// Each layer is poured while the bottle rocks from one tilt to another and back (`waves` times),
// which is how sand-art waves are made by hand.
import { writeFileSync } from 'fs';
import { Sand } from '../../../../works/sand/js/sim.js';
import GEO from '../../../../works/sand/js/geo.js';

// [sand, share of a layer, tilt from, tilt to, rocking waves]
const LAYERS = [[3, 1.1, -10, 10, 1], [2, 0.6, 12, -12, 2], [1, 0.9, -14, 14, 2], [5, 0.5, 14, -6, 1], [4, 0.8, -12, 12, 2],
  [3, 0.5, 10, -14, 1], [2, 0.7, -14, 14, 2], [1, 0.7, 12, -10, 2], [5, 0.5, -8, 12, 1], [4, 0.6, 12, -12, 2],
  [2, 0.6, -10, 10, 2], [3, 0.6, 8, -8, 1]];
const START = LAYERS.slice(0, 4);
const STILL = LAYERS;
const SUB = 40;

export function pour(sim, plan) {
  for (const [c, amt, from, to, waves] of plan) {
    const total = Math.round((sim.capacity / 13) * amt);
    for (let n = 0; n < SUB; n++) {
      const u = n / (SUB - 1);
      sim.setTilt(from + (to - from) * (0.5 - 0.5 * Math.cos(u * Math.PI * waves)));
      sim.pourInstant(c, Math.round(total / SUB), () => (sim.rand() - 0.5) * 4, false);
    }
    sim.setTilt(0);
    sim.settle();
  }
  return sim;
}

function encode(sim) {
  const out = [];
  let cur = -1, run = 0;
  for (let y = sim.mouth; y < sim.bottom; y++) {
    for (let x = sim.rowMin[y]; x <= sim.rowMax[y]; x++) {
      const v = sim.g[y * sim.W + x];
      const c = v === 0 ? 0 : v >> 5;
      if (c === cur) run++;
      else { if (run) out.push(cur, run); cur = c; run = 1; }
    }
  }
  out.push(cur, run);
  // compact text: the colour as a capital letter (A = empty, B..F = the five sands), then the run
  // length in lower-case base 36
  let s = '';
  for (let k = 0; k < out.length; k += 2) s += 'ABCDEF'[out[k]] + out[k + 1].toString(36);
  return s;
}

function fresh() {
  const sim = new Sand(GEO, 20261110);
  sim.setOutput(new Uint32Array(GEO.W * GEO.H), new Uint32Array(256 * 8));
  return sim;
}

const start = pour(fresh(), START);
const still = pour(fresh(), STILL);
const a = encode(start), b = encode(still);
writeFileSync(new URL('../../../../works/sand/js/start.js', import.meta.url),
  '// Generated by design/works/sand/scripts/prefill_build.mjs: the opening bottles, as colour runs\n' +
  '// over the interior cells row by row (A = empty, B..F = the five sands, then the run in lower-case base 36).\n' +
  `export const START = '${a}';\nexport const START_LAYERS = [${START.map((l) => l[0]).join(', ')}];\n` +
  `export const STILL = '${b}';\nexport const STILL_LAYERS = [${STILL.map((l) => l[0]).join(', ')}];\n`);
console.log('start', start.count, 'grains', (start.fill() * 100).toFixed(1) + '%', a.length, 'chars;',
  'still', still.count, 'grains', (still.fill() * 100).toFixed(1) + '%', b.length, 'chars');

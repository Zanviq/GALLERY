"""Subset Black And White Picture to the characters the sand page uses and self-host it.

    <fontenv python> -I design/works/sand/scripts/fonts.py

Scans works/sand/index.html and js/*.js for every character, asks the Google Fonts css2 API
for a `text=` subset (woff2), saves works/sand/fonts/bwp.woff2 and writes works/sand/css/fonts.css.
Re-run whenever copy changes, then run fontcheck.py.
"""
import pathlib
import re
import sys
import urllib.parse
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[4]
SITE = ROOT / 'works' / 'sand'
UA = ('Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 '
      '(KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36')


def used_chars():
    text = (SITE / 'index.html').read_text(encoding='utf-8')
    for js in sorted((SITE / 'js').rglob('*.js')):
        text += js.read_text(encoding='utf-8')
    chars = set(ch for ch in text if ord(ch) >= 32 and ch not in '﻿')
    chars |= set(chr(c) for c in range(32, 127))
    return ''.join(sorted(chars))


def fetch(url, binary=False):
    req = urllib.request.Request(url, headers={'User-Agent': UA})
    with urllib.request.urlopen(req, timeout=60) as r:
        data = r.read()
    return data if binary else data.decode('utf-8')


def main():
    chars = used_chars()
    print(len(chars), 'unique characters')
    url = ('https://fonts.googleapis.com/css2?family=' + urllib.parse.quote('Black And White Picture')
           + '&display=swap&text=' + urllib.parse.quote(chars, safe=''))
    css = fetch(url)
    srcs = re.findall(r'src:\s*url\(([^)]+)\)\s*format\([\'"]?woff2', css)
    if len(srcs) != 1:
        sys.exit(f'expected one woff2, got {len(srcs)}\n{css[:400]}')
    data = fetch(srcs[0], binary=True)
    (SITE / 'fonts').mkdir(exist_ok=True)
    (SITE / 'fonts' / 'bwp.woff2').write_bytes(data)
    print(f'bwp.woff2  {len(data) / 1024:.1f} KB')
    (SITE / 'css' / 'fonts.css').write_text(
        '/* Generated by design/works/sand/scripts/fonts.py: a subset of Black And White Picture\n'
        '   (SIL OFL 1.1, Google Fonts build, no Reserved Font Name) holding only the characters\n'
        '   this page uses. Licence: ../fonts/OFL.txt */\n'
        '@font-face {\n'
        "  font-family: 'Black And White Picture';\n"
        "  src: url('../fonts/bwp.woff2') format('woff2');\n"
        '  font-weight: 400;\n'
        '  font-style: normal;\n'
        '  font-display: swap;\n'
        '}\n', encoding='utf-8')
    print('wrote css/fonts.css')


if __name__ == '__main__':
    main()

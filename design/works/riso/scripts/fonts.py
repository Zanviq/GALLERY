"""Subset the riso work's two fonts to the characters it uses and self-host them.

    <scratchpad>/fontenv/Scripts/python.exe -I design/works/riso/scripts/fonts.py

Scans works/riso/index.html and js/*.js, asks the Google Fonts css2 API for a `text=` subset of
each face (woff2), writes works/riso/fonts/*.woff2 and works/riso/css/fonts.css, then checks with
fontTools that every character is really in the files. Re-run whenever copy changes.
Both families are SIL OFL 1.1.
"""
import html
import io
import pathlib
import re
import sys
import urllib.parse
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[4]
SITE = ROOT / 'works' / 'riso'
OUT = SITE / 'fonts'
UA = ('Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 '
      '(KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36')

FACES = [
    # (file stem, css family, google family query, which text set)
    ('black-han-sans', 'Black Han Sans', 'Black Han Sans', 'display'),
    ('gowun-dodum', 'Gowun Dodum', 'Gowun Dodum', 'all'),
]


def display_chars():
    """Only what Black Han Sans sets: headings, labels in dt/th, the brand, figures."""
    page = html.unescape((SITE / 'index.html').read_text(encoding='utf-8'))
    parts = re.findall(r'<(h[1-3]|dt|th|legend)[^>]*>(.*?)</\1>', page, flags=re.S)
    parts = [p[1] for p in parts]
    parts += re.findall(r'class="(?:brand__name|slip__title|foot__brand)"[^>]*>(.*?)<', page, flags=re.S)
    text = re.sub(r'<[^>]+>', '', ' '.join(parts))
    chars = set(ch for ch in text if ord(ch) >= 32)
    chars |= set(chr(c) for c in range(32, 127))
    chars |= set('겹원장')
    return ''.join(sorted(chars))


def used_chars():
    text = (SITE / 'index.html').read_text(encoding='utf-8')
    text = html.unescape(text)
    for js in sorted((SITE / 'js').rglob('*.js')):
        text += js.read_text(encoding='utf-8')
    chars = set(ch for ch in text if ord(ch) >= 32)
    chars |= set(chr(c) for c in range(32, 127))   # printable ASCII for typed input
    chars |= set('·–—‘’“”…×−')
    chars.discard('﻿')
    return ''.join(sorted(chars))


def fetch(url, binary=False):
    req = urllib.request.Request(url, headers={'User-Agent': UA})
    with urllib.request.urlopen(req, timeout=60) as r:
        data = r.read()
    return data if binary else data.decode('utf-8')


def main():
    sets = {'all': used_chars(), 'display': display_chars()}
    print({k: len(v) for k, v in sets.items()}, 'unique characters')
    OUT.mkdir(exist_ok=True)
    rules = []
    missing_any = False
    from fontTools.ttLib import TTFont
    for stem, family, query, which in FACES:
        chars = sets[which]
        url = ('https://fonts.googleapis.com/css2?family=' + urllib.parse.quote(query, safe=':@;.,')
               + '&display=swap&text=' + urllib.parse.quote(chars, safe=''))
        css = fetch(url)
        srcs = re.findall(r'src:\s*url\(([^)]+)\)\s*format\([\'"]?woff2', css)
        if len(srcs) != 1:
            sys.exit(f'{stem}: expected one woff2, got {len(srcs)}\n{css[:400]}')
        data = fetch(srcs[0], binary=True)
        (OUT / f'{stem}.woff2').write_bytes(data)
        font = TTFont(io.BytesIO(data))
        cmap = font.getBestCmap()
        missing = [c for c in chars if ord(c) not in cmap and not c.isspace()]
        print(f'{stem}.woff2  {len(data) / 1024:.1f} KB  missing: {"".join(missing) or "none"}')
        if missing:
            missing_any = True
        rules.append(
            '@font-face {\n'
            f"  font-family: '{family}';\n"
            f"  src: url('../fonts/{stem}.woff2') format('woff2');\n"
            '  font-weight: 400;\n'
            '  font-style: normal;\n'
            '  font-display: swap;\n'
            '}\n')
    header = ('/* Generated by design/works/riso/scripts/fonts.py: subsets of Black Han Sans and\n'
              '   Gowun Dodum (both SIL OFL 1.1) holding only the characters this page uses. */\n')
    (SITE / 'css' / 'fonts.css').write_text(header + '\n'.join(rules), encoding='utf-8')
    print('wrote css/fonts.css')
    if missing_any:
        print('NOTE: some characters are not in a face (the family lacks them); check they are only used where a fallback is fine.')


if __name__ == '__main__':
    main()

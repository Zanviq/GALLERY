"""Subset Do Hyeon and Sunflower to the characters the futsal page uses and self-host them.

    <fontenv>/python.exe -I design/works/futsal/scripts/fonts.py

Scans works/futsal/index.html and js/**/*.js for every character, asks the Google Fonts css2
API for a `text=` subset of each face (woff2), saves them to works/futsal/fonts/, writes
works/futsal/css/fonts.css, fetches each family's OFL.txt from github.com/google/fonts, then
checks with fontTools that every character really is in every file. Re-run whenever copy changes.
"""
import io
import pathlib
import re
import sys
import urllib.parse
import urllib.request

from fontTools.ttLib import TTFont

sys.stdout.reconfigure(encoding='utf-8')
ROOT = pathlib.Path(__file__).resolve().parents[4]
SITE = ROOT / 'works' / 'futsal'
OUT = SITE / 'fonts'
UA = ('Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 '
      '(KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36')

FACES = [
    # file stem, css family, google query, weight
    ('do-hyeon-400', 'Do Hyeon', 'Do Hyeon', 400),
    ('sunflower-500', 'Sunflower', 'Sunflower:wght@500', 500),
    ('sunflower-700', 'Sunflower', 'Sunflower:wght@700', 700),
]
LICENCES = [('OFL-DoHyeon.txt', 'dohyeon'), ('OFL-Sunflower.txt', 'sunflower')]


def used_chars():
    text = (SITE / 'index.html').read_text(encoding='utf-8')
    for js in sorted((SITE / 'js').rglob('*.js')):
        text += js.read_text(encoding='utf-8')
    text = text.replace('&amp;', '&')
    chars = set(ch for ch in text if ord(ch) >= 32)
    chars |= set(chr(c) for c in range(32, 127))
    chars.discard(chr(0xFEFF))
    chars.discard('`')  # JS template-literal syntax only; Sunflower has no backtick and none is displayed
    return ''.join(sorted(chars))


def fetch(url, binary=False):
    req = urllib.request.Request(url, headers={'User-Agent': UA})
    with urllib.request.urlopen(req, timeout=60) as r:
        data = r.read()
    return data if binary else data.decode('utf-8')


def main():
    chars = used_chars()
    print(len(chars), 'unique characters')
    OUT.mkdir(exist_ok=True)
    rules = []
    missing_any = False
    for stem, family, query, weight in FACES:
        url = ('https://fonts.googleapis.com/css2?family=' + urllib.parse.quote(query, safe=':@;.,')
               + '&display=swap&text=' + urllib.parse.quote(chars, safe=''))
        css = fetch(url)
        srcs = re.findall(r'src:\s*url\(([^)]+)\)\s*format\([\'"]?woff2', css)
        if len(srcs) != 1:
            sys.exit(f'{stem}: expected one woff2, got {len(srcs)}\n{css[:400]}')
        data = fetch(srcs[0], binary=True)
        path = OUT / f'{stem}.woff2'
        path.write_bytes(data)
        cmap = TTFont(io.BytesIO(data)).getBestCmap()
        missing = [c for c in chars if ord(c) not in cmap and not c.isspace()]
        if missing:
            missing_any = True
        print(f'{path.name}  {len(data) / 1024:.1f} KB  glyphs {len(cmap)}  missing {"".join(missing) or "-"}')
        rules.append(
            '@font-face {\n'
            f"  font-family: '{family}';\n"
            f"  src: url('../fonts/{stem}.woff2') format('woff2');\n"
            f'  font-weight: {weight};\n'
            '  font-style: normal;\n'
            '  font-display: swap;\n'
            '}\n')
    header = ('/* Generated by design/works/futsal/scripts/fonts.py: Do Hyeon and Sunflower\n'
              '   (both SIL OFL 1.1), subset to the characters this page uses. */\n')
    (SITE / 'css' / 'fonts.css').write_text(header + '\n'.join(rules), encoding='utf-8')
    print('wrote css/fonts.css')
    for name, folder in LICENCES:
        dest = OUT / name
        if not dest.exists():
            dest.write_bytes(fetch(f'https://raw.githubusercontent.com/google/fonts/main/ofl/{folder}/OFL.txt', binary=True))
        head = dest.read_text(encoding='utf-8', errors='replace').splitlines()[:4]
        print(name, '|', ' / '.join(h.strip() for h in head if h.strip()))
    if missing_any:
        sys.exit('some characters are missing from the subset')


if __name__ == '__main__':
    main()

"""Subset East Sea Dokdo and Hi Melody to the characters works/stamp can show, and check coverage.

    <fontenv>/python -I design/works/stamp/scripts/fonts.py <dir with EastSeaDokdo-Regular.ttf, HiMelody-Regular.ttf>
    <fontenv>/python -I design/works/stamp/scripts/fonts.py --check

Both families are from github.com/google/fonts (ofl/eastseadokdo, ofl/himelody), SIL OFL 1.1 with no
Reserved Font Name, so the subsets keep their names. Every character in index.html and js/*.js goes
into both subsets (the game writes the same words in print and in marker). Re-run after copy changes.
"""
import pathlib
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

sys.stdout.reconfigure(encoding='utf-8')
ROOT = pathlib.Path(__file__).resolve().parents[4]
SITE = ROOT / 'works' / 'stamp'
FACES = [
    ('dokdo', 'East Sea Dokdo', 'EastSeaDokdo-Regular.ttf'),
    ('himelody', 'Hi Melody', 'HiMelody-Regular.ttf'),
]


def used_chars():
    text = (SITE / 'index.html').read_text(encoding='utf-8')
    for js in sorted((SITE / 'js').glob('*.js')):
        if js.name == 'seal-data.js':
            continue
        text += js.read_text(encoding='utf-8')
    chars = set(ch for ch in text if ord(ch) >= 32 and not ch.isspace())
    chars |= set(chr(c) for c in range(33, 127))
    chars |= set('×·…‘’“”')
    chars.discard('﻿')
    return chars


def check():
    chars = used_chars()
    bad = 0
    for stem, family, _ in FACES:
        cmap = TTFont(SITE / 'fonts' / f'{stem}.woff2').getBestCmap()
        missing = sorted(ch for ch in chars if ord(ch) not in cmap)
        print(f'{family}: {len(chars)} characters used, missing: {"".join(missing) if missing else "none"}')
        bad += len(missing)
    return bad


def main():
    if sys.argv[1:] == ['--check']:
        sys.exit(1 if check() else 0)
    src = pathlib.Path(sys.argv[1])
    chars = used_chars()
    for stem, family, fname in FACES:
        font = TTFont(src / fname)
        cmap = font.getBestCmap()
        absent = sorted(ch for ch in chars if ord(ch) not in cmap)
        if absent:
            print(f'{family} lacks: {"".join(absent)}')
        opts = subset.Options()
        opts.flavor = 'woff2'
        opts.layout_features = ['kern', 'liga', 'calt', 'ccmp', 'locl']
        opts.hinting = False
        opts.desubroutinize = True
        opts.name_IDs = ['*']
        opts.notdef_outline = True
        sub = subset.Subsetter(opts)
        sub.populate(text=''.join(sorted(chars)))
        sub.subset(font)
        font.flavor = 'woff2'
        out = SITE / 'fonts' / f'{stem}.woff2'
        font.save(out)
        print(f'{out.name}: {out.stat().st_size / 1024:.1f} KB')
    css = ['/* Generated by design/works/stamp/scripts/fonts.py: subsets of East Sea Dokdo and Hi Melody\n'
           '   (YoonDesign, SIL OFL 1.1, see ../fonts/OFL.txt) holding only the characters this game shows. */\n']
    for stem, family, _ in FACES:
        css.append('@font-face {\n'
                   f"  font-family: '{family}';\n"
                   f"  src: url('../fonts/{stem}.woff2') format('woff2');\n"
                   '  font-weight: 400;\n  font-style: normal;\n  font-display: swap;\n}\n')
    (SITE / 'css' / 'fonts.css').write_text('\n'.join(css), encoding='utf-8')
    print(len(chars), 'characters')
    check()


if __name__ == '__main__':
    main()

// Carves the seal of 구도담 (round, three syllables) as SVG path data and writes:
//   works/stamp/js/seal-data.js   path strings the game turns into Path2D
//   works/stamp/img/favicon.svg   the seal as the tab icon
//   design/works/stamp/seal.svg   a large preview
//   node design/works/stamp/scripts/seal.mjs
// Strokes are straight, square-cut bars on a 100-unit grid. Corners are chamfered and nudged by a
// seeded jitter so the cut looks hand-carved; strokes run into the rim and are clipped by a circle.
import { writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import path from 'path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../../..');
let s = 0x5eed17;
const rnd = () => { s |= 0; s = (s + 0x6d2b79f5) | 0; let t = Math.imul(s ^ (s >>> 15), 1 | s); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
const j = (a) => (rnd() * 2 - 1) * a;
const f = (n) => (Math.round(n * 100) / 100).toString();

const W = 5.4; // stroke width
// [x0, y0, x1, y1] bars; reading order: 구 (right column), 도 (left top), 담 (left bottom)
const H = (x0, x1, y) => [x0, y, x1, y + W];
const V = (x, y0, y1) => [x, y0, x + W, y1];
const BARS = [
  // 구
  H(55, 90, 18), V(76.6, 18, 43.5),
  H(53.5, 97, 50.2), V(67.4, 55, 97),
  // 도
  H(18, 46, 13.2), V(18, 13.2, 33.6), H(18, 46.5, 28.2),
  V(29.6, 33, 39.6), H(4, 47, 39.2),
  // 담
  H(12.5, 30.8, 49.6), V(12.5, 49.6, 63.6), H(12.5, 31.2, 58.2),
  V(35.4, 48.2, 67.2), H(40.6, 47.4, 55.4),
  H(21, 46, 69.2), H(21, 46, 80.8), V(21, 69.2, 92), V(40.6, 69.2, 86.2),
];

function bar([x0, y0, x1, y1]) {
  const c = 0.55; // chamfer
  const pts = [
    [x0 + c, y0], [x1 - c, y0], [x1, y0 + c], [x1, y1 - c],
    [x1 - c, y1], [x0 + c, y1], [x0, y1 - c], [x0, y0 + c],
  ].map(([x, y]) => [x + j(0.28), y + j(0.28)]);
  return 'M' + pts.map(([x, y]) => f(x) + ' ' + f(y)).join('L') + 'Z';
}

function ring(r, n, cw, phase) {
  const pts = [];
  for (let i = 0; i < n; i++) {
    const a = (i / n) * Math.PI * 2;
    const rr = r + 0.22 * Math.sin(a * 3 + phase) + 0.14 * Math.sin(a * 7 + phase * 2) + j(0.08);
    pts.push([50 + Math.cos(a) * rr, 50 + Math.sin(a) * rr]);
  }
  if (!cw) pts.reverse();
  return 'M' + pts.map(([x, y]) => f(x) + ' ' + f(y)).join('L') + 'Z';
}

const glyphs = BARS.map(bar).join('');
const rim = ring(47.6, 120, true, 0.4) + ring(42.3, 120, false, 1.7);
const CLIP_R = 43;

writeFileSync(path.join(ROOT, 'works/stamp/js/seal-data.js'),
  '// Generated by design/works/stamp/scripts/seal.mjs: the seal of 구도담, carved on a 100-unit grid.\n' +
  `export const SEAL_RIM = '${rim}';\n` +
  `export const SEAL_GLYPHS = '${glyphs}';\n` +
  `export const SEAL_CLIP_R = ${CLIP_R};\n`);

const svg = (size, fill, bg) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" width="${size}" height="${size}">` +
  (bg ? `<rect width="100" height="100" fill="${bg}"/>` : '') +
  `<defs><clipPath id="c"><circle cx="50" cy="50" r="${CLIP_R}"/></clipPath></defs>` +
  `<path fill="${fill}" d="${rim}"/><path fill="${fill}" clip-path="url(#c)" d="${glyphs}"/></svg>\n`;

writeFileSync(path.join(ROOT, 'works/stamp/img/favicon.svg'), svg(32, '#C8102E'));
writeFileSync(path.join(ROOT, 'design/works/stamp/seal.svg'), svg(600, '#C8102E', '#FFFFFF'));
console.log('rim', rim.length, 'glyph', glyphs.length, 'chars');

"""Subset Gothic A1 to the characters the optician page uses and self-host it.

    <fontenv>/python.exe -I design/works/optician/scripts/fonts.py

Scans works/optician/index.html and js/*.js for every character, asks the Google Fonts
css2 API for a `text=` subset of each weight (woff2), saves them to works/optician/fonts/,
writes works/optician/css/fonts.css, then checks with fontTools that every character
really is in every file. Re-run whenever copy changes.
"""
import io
import pathlib
import re
import sys
import urllib.parse
import urllib.request

from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parents[4]
SITE = ROOT / 'works' / 'optician'
OUT = SITE / 'fonts'
UA = ('Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 '
      '(KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36')
WEIGHTS = (400, 700, 900)


def used_chars():
    text = (SITE / 'index.html').read_text(encoding='utf-8')
    for js in sorted((SITE / 'js').rglob('*.js')):
        text += js.read_text(encoding='utf-8')
    text = text.replace('&amp;', '&')
    chars = set(ch for ch in text if ord(ch) >= 32)
    chars |= set(chr(c) for c in range(32, 127))
    chars |= set('·–—−×□✓')
    chars.discard('﻿')
    return ''.join(sorted(chars))


def fetch(url, binary=False):
    req = urllib.request.Request(url, headers={'User-Agent': UA})
    with urllib.request.urlopen(req, timeout=60) as r:
        data = r.read()
    return data if binary else data.decode('utf-8')


def main():
    chars = used_chars()
    print(len(chars), 'unique characters')
    OUT.mkdir(exist_ok=True)
    rules = []
    missing_any = False
    for w in WEIGHTS:
        url = ('https://fonts.googleapis.com/css2?family=' + urllib.parse.quote(f'Gothic A1:wght@{w}', safe=':@;.,')
               + '&display=swap&text=' + urllib.parse.quote(chars, safe=''))
        css = fetch(url)
        srcs = re.findall(r'src:\s*url\(([^)]+)\)\s*format\([\'"]?woff2', css)
        if len(srcs) != 1:
            sys.exit(f'{w}: expected one woff2, got {len(srcs)}\n{css[:400]}')
        data = fetch(srcs[0], binary=True)
        path = OUT / f'gothic-a1-{w}.woff2'
        path.write_bytes(data)
        cmap = TTFont(io.BytesIO(data)).getBestCmap()
        missing = [c for c in chars if ord(c) not in cmap and not c.isspace()]
        if missing:
            missing_any = True
        print(f'{path.name}  {len(data) / 1024:.1f} KB  glyphs {len(cmap)}  missing {"".join(missing) or "-"}')
        rules.append(
            '@font-face {\n'
            "  font-family: 'Gothic A1';\n"
            f"  src: url('../fonts/gothic-a1-{w}.woff2') format('woff2');\n"
            f'  font-weight: {w};\n'
            '  font-style: normal;\n'
            '  font-display: swap;\n'
            '}\n')
    header = ('/* Generated by design/works/optician/scripts/fonts.py: Gothic A1 (SIL OFL 1.1),\n'
              '   subset to the characters this page uses. */\n')
    (SITE / 'css' / 'fonts.css').write_text(header + '\n'.join(rules), encoding='utf-8')
    print('wrote css/fonts.css')
    if missing_any:
        sys.exit('some characters are missing from the subset')


if __name__ == '__main__':
    main()

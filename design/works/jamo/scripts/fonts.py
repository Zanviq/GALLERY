"""Subset Orbit to the glyphs this game can show and write the list of syllables it has.

    <fontenv>/python -I design/works/jamo/scripts/fonts.py <path to Orbit-Regular.ttf>

Orbit-Regular.ttf comes from github.com/google/fonts (ofl/orbit). The subset holds:
- every character in works/jamo/index.html and works/jamo/js/*.js (page copy, messages, clues),
- every compatibility jamo (tiles and blocks draw them),
- every syllable a player can build in any puzzle (computed from js/puzzles.js with the same stroke
  rules as the game) that Orbit has. Orbit covers 2,780 syllables; the game assembles the others
  from jamo pieces, so js/glyphs.js lists which composed syllables the font can draw.
Re-run after changing copy or puzzles.
"""
import io
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from fontTools import subset  # noqa: E402
from fontTools.ttLib import TTFont  # noqa: E402

import check_puzzles  # noqa: E402
from hangul import SITE  # noqa: E402

sys.stdout.reconfigure(encoding='utf-8')


def page_chars():
    text = (SITE / 'index.html').read_text(encoding='utf-8')
    for js in sorted((SITE / 'js').glob('*.js')):
        if js.name == 'glyphs.js':
            continue
        text += js.read_text(encoding='utf-8')
    chars = set(ch for ch in text if ord(ch) >= 32)
    chars |= set(chr(c) for c in range(32, 127))
    chars |= set(chr(c) for c in range(0x3131, 0x3164))  # compatibility jamo ㄱ..ㅣ
    chars.discard('﻿')
    return chars


def main():
    src = sys.argv[1]
    font = TTFont(src)
    cmap = font.getBestCmap()
    data = check_puzzles.load_puzzles()
    reach = set()
    for p in data['LESSONS'] + data['PUZZLES']:
        reach |= check_puzzles.reachable(p)
    have = sorted(s for s in reach if ord(s) in cmap)
    chars = page_chars() | set(have)
    missing = sorted(ch for ch in chars if ord(ch) not in cmap and not ch.isspace())
    if missing:
        print('NOT IN ORBIT (will fall back):', ''.join(missing))
    opts = subset.Options()
    opts.flavor = 'woff2'
    opts.layout_features = ['kern', 'liga', 'calt', 'ccmp', 'locl']
    opts.hinting = False
    opts.desubroutinize = True
    opts.name_IDs = ['*']
    opts.notdef_outline = True
    sub = subset.Subsetter(opts)
    sub.populate(text=''.join(sorted(chars)))
    sub.subset(font)
    out = SITE / 'fonts' / 'orbit.woff2'
    font.flavor = 'woff2'
    font.save(out)
    # every syllable Orbit can draw that is also in the subset (page copy included)
    syl = sorted(ch for ch in chars if 0xAC00 <= ord(ch) <= 0xD7A3 and ord(ch) in cmap)
    (SITE / 'js' / 'glyphs.js').write_text(
        '// Generated by design/works/jamo/scripts/fonts.py: composed syllables in fonts/orbit.woff2.\n'
        f'export const HAVE = new Set({"".join(syl)!r});\n'.replace("Set('", 'Set([...\'').replace("');", "']);"),
        encoding='utf-8')
    print(f'{len(chars)} characters, {len(syl)} syllables, reachable in font {len(have)} of {len(reach)};'
          f' {out.name} {os.path.getsize(out) / 1024:.1f} KB')


if __name__ == '__main__':
    main()

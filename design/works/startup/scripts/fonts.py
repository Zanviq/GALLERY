"""Subset the site's fonts to the characters it actually uses and self-host them.

    python -I design/works/startup/scripts/fonts.py

Scans works/startup/index.html and js/*.js for every character, asks the Google Fonts
css2 API for a `text=` subset of each face (woff2), downloads the files into
works/startup/fonts/ and writes works/startup/css/fonts.css.
Re-run whenever copy changes.
"""
import pathlib
import re
import sys
import urllib.parse
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[4]
SITE = ROOT / 'works' / 'startup'
OUT = SITE / 'fonts'
UA = ('Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 '
      '(KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36')

FACES = [
    # (file stem, css family, google family query, css weight descriptor, text set)
    ('hahmlet', 'Hahmlet', 'Hahmlet:wght@500..650', '500 650', 'display'),
    ('plex-kr-400', 'Mulgil Sans', 'IBM Plex Sans KR:wght@400', '400', 'all'),
    ('plex-kr-500', 'Mulgil Sans', 'IBM Plex Sans KR:wght@500', '500', 'all'),
    ('plex-kr-600', 'Mulgil Sans', 'IBM Plex Sans KR:wght@600', '600', 'all'),
]


def display_chars():
    """Only what Hahmlet sets: headings, the wordmark, the HUD title, chart water names."""
    html = (SITE / 'index.html').read_text(encoding='utf-8')
    parts = re.findall(r'<h[1-4][^>]*>(.*?)</h[1-4]>', html, flags=re.S)
    parts += re.findall(r'class="(?:brand__name|hud__title)"[^>]*>(.*?)</(?:span|p)>', html, flags=re.S)
    world = (SITE / 'js' / 'chart' / 'world.js').read_text(encoding='utf-8')
    parts += re.findall(r"text: '([^']+)'", world)
    text = re.sub(r'<[^>]+>', '', ' '.join(parts))
    chars = set(ch for ch in text if ord(ch) >= 32)
    chars |= set(chr(c) for c in range(32, 127))
    return ''.join(sorted(chars))


def used_chars():
    text = (SITE / 'index.html').read_text(encoding='utf-8')
    for js in sorted((SITE / 'js').rglob('*.js')):
        text += js.read_text(encoding='utf-8')
    # decode the few HTML entities we use
    text = text.replace('&amp;', '&')
    chars = set(ch for ch in text if ord(ch) >= 32)
    chars |= set(chr(c) for c in range(32, 127))   # full printable ASCII for form input
    chars |= set('·–—‘’“”…×°′″−→←↑↓³²₀₁₂₃₄₅₆₇₈₉%')
    chars.discard('﻿')
    return ''.join(sorted(chars))


def fetch(url, binary=False):
    req = urllib.request.Request(url, headers={'User-Agent': UA})
    with urllib.request.urlopen(req, timeout=60) as r:
        data = r.read()
    return data if binary else data.decode('utf-8')


def main():
    sets = {'all': used_chars(), 'display': display_chars()}
    print({k: len(v) for k, v in sets.items()}, 'unique characters')
    OUT.mkdir(exist_ok=True)
    rules = []
    for stem, family, query, weight, which in FACES:
        chars = sets[which]
        url = ('https://fonts.googleapis.com/css2?family=' + urllib.parse.quote(query, safe=':@;.,')
               + '&display=swap&text=' + urllib.parse.quote(chars, safe=''))
        css = fetch(url)
        srcs = re.findall(r'src:\s*url\(([^)]+)\)\s*format\([\'"]?woff2', css)
        if len(srcs) != 1:
            sys.exit(f'{stem}: expected one woff2, got {len(srcs)}\n{css[:400]}')
        data = fetch(srcs[0], binary=True)
        (OUT / f'{stem}.woff2').write_bytes(data)
        print(f'{stem}.woff2  {len(data) / 1024:.1f} KB')
        rules.append(
            '@font-face {\n'
            f"  font-family: '{family}';\n"
            f"  src: url('../fonts/{stem}.woff2') format('woff2');\n"
            f'  font-weight: {weight};\n'
            '  font-style: normal;\n'
            '  font-display: swap;\n'
            '}\n')
    header = ('/* Generated by design/works/startup/scripts/fonts.py — subsets of Hahmlet and\n'
              '   IBM Plex Sans KR (both SIL OFL 1.1) holding only the characters this page uses. */\n')
    (SITE / 'css' / 'fonts.css').write_text(header + '\n'.join(rules), encoding='utf-8')
    print('wrote css/fonts.css')


if __name__ == '__main__':
    main()

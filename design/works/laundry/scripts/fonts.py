"""Subset the two families to the characters works/laundry actually uses.

    <fontenv>/python.exe -I design/works/laundry/scripts/fonts.py <dir with source TTFs>

Sources (downloaded once into the scratch folder, not kept in the repo):
  Jua-Regular.ttf             github.com/google/fonts/ofl/jua  (OFL 1.1, no Reserved Font Name)
  NanumSquareRound{R,B,EB}.ttf  hangeul.pstatic.net/hangeul_static/webfont/NanumSquareRound/ (NAVER, OFL 1.1)

"NanumSquareRound" is a Reserved Font Name. A subset is a Modified Version under the OFL,
so the subset is renamed inside the font ("Ppodeuk Round") and in CSS. Copyright and licence
records are kept. Re-run whenever copy changes; it fails if any character is missing.
"""
import html
import pathlib
import re
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parents[4]
SITE = ROOT / 'works' / 'laundry'
OUT = SITE / 'fonts'
SRC = pathlib.Path(sys.argv[1])

FACES = [
    # (source, out stem, css family, weight, new family, style name)
    ('Jua-Regular.ttf', 'jua', 'Jua', 400, None, None),
    ('NanumSquareRoundR.ttf', 'ppodeuk-round-400', 'Ppodeuk Round', 400, 'Ppodeuk Round', 'Regular'),
    ('NanumSquareRoundB.ttf', 'ppodeuk-round-700', 'Ppodeuk Round', 700, 'Ppodeuk Round', 'Bold'),
    ('NanumSquareRoundEB.ttf', 'ppodeuk-round-800', 'Ppodeuk Round', 800, 'Ppodeuk Round', 'ExtraBold'),
]


def used_chars():
    text = (SITE / 'index.html').read_text(encoding='utf-8')
    text = re.sub(r'<!--.*?-->', '', text, flags=re.S)
    text = html.unescape(text)
    for js in sorted((SITE / 'js').glob('*.js')):
        src = js.read_text(encoding='utf-8')
        # comments out; everything else (non-ASCII only appears in strings) stays
        src = re.sub(r'(?m)^\s*//[^\n]*', '', src)
        src = re.sub(r'/\*.*?\*/', '', src, flags=re.S)
        text += src
    chars = set(ch for ch in text if ord(ch) >= 32)
    chars |= set(chr(c) for c in range(32, 127))
    chars |= set('·‘’“”…×')
    chars.discard('﻿')
    return chars


def rename(font, family, style):
    full = f'{family} {style}' if style != 'Regular' else family
    ps = family.replace(' ', '') + '-' + style
    names = {1: family if style in ('Regular', 'Bold') else f'{family} {style}', 2: style if style in ('Regular', 'Bold') else 'Regular',
             3: f'{ps};subset for gallery.zanviq.dev/laundry', 4: full, 6: ps, 16: family, 17: style}
    table = font['name']
    for rec in list(table.names):
        if rec.nameID in (1, 2, 3, 4, 6, 16, 17, 18, 21, 22):
            table.removeNames(nameID=rec.nameID, platformID=rec.platformID, platEncID=rec.platEncID, langID=rec.langID)
    for nid, val in names.items():
        table.setName(val, nid, 3, 1, 0x409)
        table.setName(val, nid, 1, 0, 0)
    note = ('Modified Version (subset) of NanumSquareRound by NAVER Corporation, renamed under the '
            'SIL Open Font License 1.1 Reserved Font Name clause.')
    table.setName(note, 10, 3, 1, 0x409)


def main():
    chars = used_chars()
    print(len(chars), 'unique characters')
    OUT.mkdir(exist_ok=True)
    rules = []
    for src, stem, family, weight, newfam, style in FACES:
        font = TTFont(SRC / src)
        cmap = font.getBestCmap()
        missing = sorted(ch for ch in chars if ord(ch) not in cmap and not ch.isspace())
        if missing:
            print(f'{stem}: not in source font:', ' '.join(f'U+{ord(c):04X}' for c in missing))
        opts = subset.Options()
        opts.flavor = 'woff2'
        opts.layout_features = ['kern', 'liga', 'calt', 'ccmp', 'locl', 'mark', 'mkmk', 'tnum']
        opts.name_IDs = ['*']
        opts.name_languages = ['*']
        opts.notdef_outline = True
        opts.hinting = False
        sub = subset.Subsetter(opts)
        sub.populate(unicodes=[ord(c) for c in chars])
        sub.subset(font)
        if newfam:
            rename(font, newfam, style)
        path = OUT / f'{stem}.woff2'
        font.flavor = 'woff2'
        font.save(path)
        print(f'{path.name}  {path.stat().st_size / 1024:.1f} KB')
        rules.append('@font-face {\n'
                     f"  font-family: '{family}';\n"
                     f"  src: url('../fonts/{stem}.woff2') format('woff2');\n"
                     f'  font-weight: {weight};\n'
                     '  font-style: normal;\n'
                     '  font-display: swap;\n'
                     '}\n')
    header = ('/* Generated by design/works/laundry/scripts/fonts.py. Subsets holding only the characters this page uses.\n'
              '   Jua: SIL OFL 1.1 (fonts/OFL-Jua.txt).\n'
              '   Ppodeuk Round: a renamed subset of NAVER NanumSquareRound, SIL OFL 1.1 (fonts/OFL-NanumSquareRound.txt). */\n')
    (SITE / 'css' / 'fonts.css').write_text(header + '\n'.join(rules), encoding='utf-8')
    print('wrote css/fonts.css')


if __name__ == '__main__':
    main()

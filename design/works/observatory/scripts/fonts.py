"""Subset Nanum Myeongjo and Nanum Gothic Coding to the characters the observatory page uses.

    <fontenv>/python.exe -I design/works/observatory/scripts/fonts.py

Scans works/observatory/index.html and js/*.js (canvas labels, star names, list copy), asks the
Google Fonts css2 API for a `text=` subset of each face (woff2), saves them to
works/observatory/fonts/, writes works/observatory/css/fonts.css, then checks with fontTools
that every character is in every file. Re-run whenever copy changes.
"""
import io
import pathlib
import re
import sys
import urllib.parse
import urllib.request

from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parents[4]
SITE = ROOT / 'works' / 'observatory'
OUT = SITE / 'fonts'
UA = ('Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 '
      '(KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36')
GREEK = 'αβγδεζηθικλμνξοπρστυφχψω'
FACES = [
    # (file stem, css family, google family, weight)
    ('nanum-myeongjo-400', 'Nanum Myeongjo', 'Nanum Myeongjo', 400),
    ('nanum-myeongjo-700', 'Nanum Myeongjo', 'Nanum Myeongjo', 700),
    ('nanum-myeongjo-800', 'Nanum Myeongjo', 'Nanum Myeongjo', 800),
    ('nanum-gothic-coding-400', 'Nanum Gothic Coding', 'Nanum Gothic Coding', 400),
    ('nanum-gothic-coding-700', 'Nanum Gothic Coding', 'Nanum Gothic Coding', 700),
]


def used_chars():
    text = (SITE / 'index.html').read_text(encoding='utf-8')
    for js in sorted((SITE / 'js').rglob('*.js')):
        text += js.read_text(encoding='utf-8')
    text = text.replace('&amp;', '&')
    chars = set(ch for ch in text if ord(ch) >= 32)
    chars |= set(chr(c) for c in range(32, 127))
    chars |= set('·–—‘’“”…×°←→↑↓²³¹')
    chars.discard('﻿')
    return ''.join(sorted(chars))


def fetch(url, binary=False):
    req = urllib.request.Request(url, headers={'User-Agent': UA})
    with urllib.request.urlopen(req, timeout=90) as r:
        data = r.read()
    return data if binary else data.decode('utf-8')


def main():
    sys.stdout.reconfigure(encoding='utf-8')
    chars = used_chars()
    print(len(chars), 'unique characters')
    OUT.mkdir(exist_ok=True)
    rules = []
    missing_all = {}
    for stem, family, gfam, w in FACES:
        url = ('https://fonts.googleapis.com/css2?family=' + urllib.parse.quote(f'{gfam}:wght@{w}', safe=':@;.,')
               + '&display=swap&text=' + urllib.parse.quote(chars, safe=''))
        css = fetch(url)
        srcs = re.findall(r'src:\s*url\(([^)]+)\)\s*format\([\'"]?woff2', css)
        if len(srcs) != 1:
            sys.exit(f'{stem}: expected one woff2, got {len(srcs)}\n{css[:400]}')
        data = fetch(srcs[0], binary=True)
        (OUT / f'{stem}.woff2').write_bytes(data)
        cmap = TTFont(io.BytesIO(data)).getBestCmap()
        # Nanum Myeongjo has no Greek; the page sets Bayer letters only in Nanum Gothic Coding
        skip = GREEK if family == 'Nanum Myeongjo' else ''
        missing = [c for c in chars if ord(c) not in cmap and not c.isspace() and c not in skip]
        missing_all[stem] = missing
        print(f'{stem}.woff2  {len(data) / 1024:.1f} KB  glyphs {len(cmap)}  missing {"".join(missing) or "-"}')
        rules.append(
            '@font-face {\n'
            f"  font-family: '{family}';\n"
            f"  src: url('../fonts/{stem}.woff2') format('woff2');\n"
            f'  font-weight: {w};\n'
            '  font-style: normal;\n'
            '  font-display: swap;\n'
            '}\n')
    header = ('/* Generated by design/works/observatory/scripts/fonts.py: Nanum Myeongjo and\n'
              '   Nanum Gothic Coding (both SIL OFL 1.1), subset to the characters this page uses. */\n')
    (SITE / 'css' / 'fonts.css').write_text(header + '\n'.join(rules), encoding='utf-8')
    print('wrote css/fonts.css')
    if any(missing_all.values()):
        sys.exit('some characters are missing from a subset')


if __name__ == '__main__':
    main()
